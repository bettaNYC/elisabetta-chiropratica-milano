let currentLang = 'it';

function applyLanguage(lang) {
    currentLang = lang;
    document.documentElement.lang = lang;
    document.title = lang === 'it'
        ? 'DR. Elisabetta Alfonsi, DACNB — Chiropratica a Milano'
        : 'Elisabetta Alfonsi DC, DACNB — Chiropractor in Milan';

    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const value = translations[lang][key];
        if (value !== undefined) {
            el.innerHTML = value.replace(/\n/g, '<br>');
        }
    });

    document.getElementById('langToggle').textContent = lang === 'it' ? 'EN' : 'IT';
}

document.getElementById('langToggle').addEventListener('click', () => {
    applyLanguage(currentLang === 'it' ? 'en' : 'it');
});

// Navbar on scroll
const navbar = document.getElementById('navbar');
window.addEventListener('scroll', () => {
    navbar.classList.toggle('scrolled', window.scrollY > 40);
}, { passive: true });

// Hamburger menu
const hamburger = document.getElementById('hamburger');
const navLinks = document.getElementById('navLinks');

hamburger.addEventListener('click', () => {
    const isOpen = navLinks.classList.toggle('open');
    hamburger.classList.toggle('open', isOpen);
    document.body.style.overflow = isOpen ? 'hidden' : '';
});

navLinks.querySelectorAll('a').forEach(link => {
    link.addEventListener('click', () => {
        navLinks.classList.remove('open');
        hamburger.classList.remove('open');
        document.body.style.overflow = '';
    });
});

// Fade-in on scroll
const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
        if (entry.isIntersecting) {
            entry.target.classList.add('visible');
            observer.unobserve(entry.target);
        }
    });
}, { threshold: 0.08 });

document.querySelectorAll('.fade-in').forEach(el => observer.observe(el));

// Contact form — shows success state (swap for real handler when ready)
document.getElementById('contactForm').addEventListener('submit', (e) => {
    e.preventDefault();
    const btn = document.getElementById('formSubmit');
    const success = document.getElementById('formSuccess');
    btn.disabled = true;
    btn.style.opacity = '0.5';
    success.classList.add('visible');
    e.target.reset();
    setTimeout(() => {
        success.classList.remove('visible');
        btn.disabled = false;
        btn.style.opacity = '';
    }, 4000);
});

// Apply Italian on load so all data-i18n elements render correctly from the start
applyLanguage('it');
